<?php

use ActiveRecord\DatabaseException;
use ActiveRecord\Table;

/**
 * Postgres: a pk the database fills itself — a serial whose sequence does not have the
 * {table}_{pk}_seq name, an IDENTITY (#47), a non-sequence default like
 * gen_random_uuid() (#153) — is read back with INSERT … RETURNING.
 * The tables are Postgres-only, so they are created and dropped around each test.
 */
class PgsqlPkFilledByDatabaseTest extends DatabaseTest
{
    private const TABLES = 't47_renamed, t47_orig, t47_always_identities, t47_default_identities, t47_no_defaults, t153_uuids';

    public function set_up($connection_name = null)
    {
        parent::set_up('pgsql');

        $this->drop_tables();
        $this->conn->query('CREATE TABLE t47_orig (id serial PRIMARY KEY, name varchar(20))');
        $this->conn->query('ALTER TABLE t47_orig RENAME TO t47_renamed');
        $this->conn->query('CREATE TABLE t47_always_identities (id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY, name varchar(20))');
        $this->conn->query('CREATE TABLE t47_default_identities (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(20))');
        $this->conn->query('CREATE TABLE t47_no_defaults (id int PRIMARY KEY, name varchar(20))');
        $this->conn->query('CREATE SEQUENCE t47_declared_seq START 500');
        $this->conn->query('CREATE TABLE t153_uuids (id uuid PRIMARY KEY DEFAULT gen_random_uuid(), name varchar(20))');
        Table::clear_cache();
    }

    public function tear_down()
    {
        $this->drop_tables();
        Table::clear_cache();
        parent::tear_down();
    }

    private function drop_tables(): void
    {
        $this->conn->query('DROP TABLE IF EXISTS ' . self::TABLES);
        $this->conn->query('DROP SEQUENCE IF EXISTS t47_declared_seq');
    }

    /**
     * @return array<string, array{class-string<ActiveRecord\Model>}>
     */
    public static function filled_pk_models(): array
    {
        return [
            'renamed serial' => [T47Renamed::class],
            'ALWAYS identity' => [T47AlwaysIdentity::class],
            'BY DEFAULT identity' => [T47DefaultIdentity::class],
        ];
    }

    #[\PHPUnit\Framework\Attributes\DataProvider('filled_pk_models')]
    public function test_create_without_id_reads_the_stored_pk_back(string $class)
    {
        $first = $class::create(['name' => 'first']);
        $this->assert_string_ends_with(' RETURNING "id"', $class::table()->last_sql);
        $this->assert_string_not_contains_string('nextval', $class::table()->last_sql);
        $this->assert_same($class::find('last')->id, $first->id);
        $this->assert_same(1, $first->id);
        $this->assert_false($first->is_new_record());

        $second = $class::create(['name' => 'second']);
        $this->assert_same(2, $second->id);

        // the pk is remembered as stored: update and delete reach the row
        $first->name = 'renamed';
        $first->save();
        $this->assert_equals('renamed', $class::find(1)->name);
        $first->delete();
        $records = $class::all(['order' => 'id']);
        $this->assert_same([2], ActiveRecord\collect($records, 'id'));
    }

    #[\PHPUnit\Framework\Attributes\DataProvider('filled_pk_models')]
    public function test_create_with_a_null_id_behaves_like_an_absent_id(string $class)
    {
        $record = $class::create(['id' => null, 'name' => 'x']);
        $this->assert_same(1, $record->id);
        $this->assert_equals('x', $class::find(1)->name);

        $record = new $class(['name' => 'y']);
        $record->id = null;
        $record->save();
        $this->assert_same(2, $record->id);
    }

    public function test_by_default_identity_stores_an_explicit_id()
    {
        $record = T47DefaultIdentity::create(['id' => 40, 'name' => 'x']);
        $this->assert_same(40, $record->id);
        $this->assert_equals('x', T47DefaultIdentity::find(40)->name);
        $this->assert_string_not_contains_string('RETURNING', T47DefaultIdentity::table()->last_sql);
    }

    public function test_always_identity_rejects_an_explicit_id()
    {
        // no OVERRIDING SYSTEM VALUE: the database's own error stands
        $this->assert_exception_message_contains('428C9', function () {
            T47AlwaysIdentity::create(['id' => 40, 'name' => 'x']);
        }, DatabaseException::class);
    }

    public function test_table_sequence_is_the_real_sequence()
    {
        $this->assert_equals('t47_orig_id_seq', T47Renamed::table()->sequence);
        $this->assert_equals('t47_orig_id_seq', T47Renamed::table()->columns['id']->sequence);
        $this->assert_equals('t47_always_identities_id_seq', T47AlwaysIdentity::table()->sequence);
        $this->assert_equals('t47_always_identities_id_seq', T47AlwaysIdentity::table()->columns['id']->sequence);
        $this->assert_equals('t47_default_identities_id_seq', T47DefaultIdentity::table()->sequence);
        $this->assert_equals('t47_default_identities_id_seq', T47DefaultIdentity::table()->columns['id']->sequence);
    }

    public function test_identity_column_keeps_no_default_and_no_auto_increment()
    {
        $column = T47AlwaysIdentity::table()->columns['id'];
        $this->assert_null($column->default);
        $this->assert_false($column->auto_increment);
    }

    public function test_standard_serial_is_unchanged()
    {
        $this->assert_equals('authors_author_id_seq', Author::table()->sequence);
        $this->assert_equals('authors_author_id_seq', Author::table()->columns['author_id']->sequence);

        $author = Author::create(['name' => 'serial']);
        $this->assert_string_ends_with(' RETURNING "author_id"', Author::table()->last_sql);
        $this->assert_true(is_int($author->id));
        $this->assert_same(Author::find('last')->id, $author->id);
    }

    public function test_declared_sequence_wins_over_the_column_default()
    {
        $this->assert_equals('t47_declared_seq', T47DeclaredSequence::table()->sequence);

        $record = T47DeclaredSequence::create(['name' => 'x']);
        $this->assert_same(500, $record->id);
        $this->assert_string_contains_string("nextval('t47_declared_seq')", T47DeclaredSequence::table()->last_sql);
        $this->assert_string_not_contains_string('RETURNING', T47DeclaredSequence::table()->last_sql);
        $this->assert_equals('x', T47Renamed::find(500)->name);
    }

    public function test_pk_without_default_keeps_the_convention()
    {
        $this->assert_equals('t47_no_defaults_id_seq', T47NoDefault::table()->sequence);
        $this->assert_null(T47NoDefault::table()->columns['id']->sequence);

        // the convention sequence does not exist: the database says so, as before
        $this->assert_exception_message_contains('t47_no_defaults_id_seq', function () {
            T47NoDefault::create(['name' => 'x']);
        }, DatabaseException::class);
        $this->assert_string_contains_string("nextval('t47_no_defaults_id_seq')", T47NoDefault::table()->last_sql);

        $this->assert_same(7, T47NoDefault::create(['id' => 7, 'name' => 'y'])->id);
    }

    public function test_uuid_default_pk_is_read_back()
    {
        $record = T153Uuid::create(['name' => 'first']);
        $this->assert_string_ends_with(' RETURNING "id"', T153Uuid::table()->last_sql);
        $this->assert_string_not_contains_string('nextval', T153Uuid::table()->last_sql);
        $this->assert_true(is_string($record->id));
        $this->assert_matches_regular_expression('/\A[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\z/', $record->id);
        $this->assert_same(T153Uuid::find_by_name('first')->id, $record->id);
        $this->assert_false($record->is_new_record());

        // the pk is remembered as stored: update and delete reach the row
        $record->name = 'renamed';
        $record->save();
        $this->assert_equals('renamed', T153Uuid::find($record->id)->name);

        $other = T153Uuid::create(['id' => null, 'name' => 'second']);
        $this->assert_not_equals($record->id, $other->id);
        $record->delete();
        $this->assert_same(['second'], array_map(fn($r) => $r->name, T153Uuid::all()));
    }

    public function test_uuid_default_pk_stores_an_explicit_id()
    {
        $id = 'a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a11';
        $record = T153Uuid::create(['id' => $id, 'name' => 'x']);
        $this->assert_same($id, $record->id);
        $this->assert_equals('x', T153Uuid::find($id)->name);
        $this->assert_string_not_contains_string('RETURNING', T153Uuid::table()->last_sql);
    }

    public function test_uuid_default_pk_has_no_sequence()
    {
        $this->assert_null(T153Uuid::table()->sequence);
        $this->assert_null(T153Uuid::table()->columns['id']->sequence);
    }

    public function test_next_sequence_value_doubles_a_quote()
    {
        $this->assert_equals("nextval('a''b')", $this->conn->next_sequence_value("a'b"));
    }
}
